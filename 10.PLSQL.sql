DELIMITER $$
CREATE FUNCTION GET_AGE (P_EMP_NO CHAR(14))
RETURNS INT -- 선언할 때에는 S 붙은 RETURN'S'
-- NOW()함수를 사용하면 함수의 실행결과가 항상 같지 않다
-- READS SQL DATA
BEGIN
	DECLARE V_AGE INT;
    SET V_AGE = TIMESTAMPDIFF(YEAR, STR_TO_DATE( CASE WHEN SUBSTRING(P_EMP_NO, 8, 1) IN ('1', '2') THEN CONCAT('19', SUBSTRING(P_EMP_NO, 1, 6))
				WHEN SUBSTRING(P_EMP_NO, 8, 1) IN ('3', '4') THEN CONCAT('20', SUBSTRING(P_EMP_NO, 1, 6))
				END, '%Y%m%d'), NOW());
    RETURN V_AGE;
END $$
DELIMITER ;

DROP FUNCTION GET_AGE; -- 펑션 삭제하기

SELECT GET_AGE(EMP_NO)
FROM EMP;



-- ---------------------------
-- 프로시저 (Stored Procedure)
-- 여러개의 DML문장을 처리
-- ---------------------------
-- 부서 코드와 인상률을 파라메터로 전달받아 부서의 사원 급여를 인상하는 PROCEDURE
DELIMITER $$
-- 변수사용 : IN/ 되돌려주는값 : OUT
CREATE PROCEDURE RAISE_SALARY(IN P_DEPT_ID CHAR(2), IN P_RATE DECIMAL(3,2), OUT P_AVG_SALARY INT)
BEGIN
	UPDATE EMP
    SET SALARY = SALARY * (1 + P_RATE)
    WHERE DEPT_ID = P_DEPT_ID;
    
    -- SELECT 문의 조회결과를 변수에 담을 수 있다.
    -- 단일 행만 가능
    SELECT AVG(SALARY) INTO P_AVG_SALARY
    FROM EMP
    WHERE DEPT_ID = P_DEPT_ID;
    
    COMMIT;
END $$
DELIMITER ;

DROP PROCEDURE RAISE_SALARY;


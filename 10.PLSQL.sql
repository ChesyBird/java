CREATE TABLE SALARY_LOG (
    LOG_ID     INT AUTO_INCREMENT PRIMARY KEY,
    EMP_ID     VARCHAR(3),
    OLD_SALARY INT,
    NEW_SALARY INT,
    CHANGED_AT DATETIME DEFAULT NOW()
); 
DELIMITER $$
CREATE PROCEDURE FLAG_LOW_SALARY()
BEGIN
	-- 변수선언
	DECLARE V_DONE INT DEFAULT 0; -- 반복문의 탈출 조건 설정준비
    DECLARE V_EMP_ID VARCHAR(3);
    DECLARE V_SALARY INT;
    
    -- 커서 선언
    DECLARE CUR CURSOR FOR
		SELECT EMP_ID, SALARY FROM EMP;
	DECLARE CONTINUE HANDLER FOR NOT FOUND SET V_DONE = 1; -- 반복문 탈출 조건2
    
    -- 쿼리의 실행, FETCH 준비
    OPEN CUR;
    READ_LOOP : LOOP
		FETCH CUR INTO V_EMP_ID, V_SALARY;
        IF V_DONE = 1 THEN
			LEAVE READ_LOOP;
        END IF;
        
	IF V_SALARY < 2000000 THEN
	-- 급여 이력 테이블
		INSERT INTO SALARY_LOG (V_EMP_ID, V_SALARY, V_SALARY);
	END IF;
    
    END LOOP;
    CLOSE CUR;
    
END $$
DELIMITER ;

-- DDL
-- DBMS에서 제공해주는 여러가지 객체를 CREATE생성, ALTER수정, DROP삭제
-- CREATE TABLE 테이블명 (
-- 	컬럼이름 타입 [제약조건],
-- 	컬럼이름 타입 [제약조건]
-- );
-- AUTO_INCREMENT : 식별자. 값을 입력하지 않아도 1부터 시작해서 1씩 증가하는 일련번호 입력
-- PrimaryKey : PK. 식별자. 중복이 될 수 없고 NULL을 입력할 수 없음 - 하나의 행을 유일무이하게 구분
-- NOT NULL : 필수입력
CREATE TABLE MEMBER (
    MEMBER_ID INT          AUTO_INCREMENT PRIMARY KEY,
    NAME      VARCHAR(20)  NOT NULL,
    PHONE     VARCHAR(20)  NOT NULL,
    ADDRESS   VARCHAR(100)
);
CREATE TABLE BOOK (
    BOOK_ID INT           AUTO_INCREMENT PRIMARY KEY,
    TITLE   VARCHAR(100)  NOT NULL,
    AUTHOR  VARCHAR(50)
);
CREATE TABLE RENTAL_STATUS_CODE (
    STATUS_CODE VARCHAR(10) PRIMARY KEY,
    STATUS_NAME VARCHAR(20) NOT NULL
);

-- 외래키 제약조건을 적용하는 경우, 참조될 테이블이 미리 생성되어있어야 한다
CREATE TABLE RENTAL (
    RENTAL_ID    INT          AUTO_INCREMENT PRIMARY KEY,
    MEMBER_ID    INT          NOT NULL,
    BOOK_ID      INT          NOT NULL,
    RENTAL_DATE  DATE         NOT NULL,
    RETURN_DATE  DATE,
    STATUS_CODE  VARCHAR(10)  NOT NULL,
    -- CONSTRAINT 제약조건이름 FOREIGN KEY (컬럼이름) REFERENCES 참조테이블명 (컬럼명)
    -- 데이터의 무결성 유지
    -- 사원테이블의 사원ID 참조하면 등록되지않은 사원ID입력시 오류가 발생
    CONSTRAINT FK_RENTAL_MEMBER FOREIGN KEY (MEMBER_ID) REFERENCES MEMBER (MEMBER_ID),
    CONSTRAINT FK_RENTAL_BOOK   FOREIGN KEY (BOOK_ID)   REFERENCES BOOK (BOOK_ID),
    CONSTRAINT FK_RENTAL_STATUS FOREIGN KEY (STATUS_CODE) REFERENCES RENTAL_STATUS_CODE (STATUS_CODE)
);

-- 테이블 삭제
DROP	TABLE RENTAL;
DROP	TABLE RENTAL_STATUS_CODE;
DROP	TABLE MEMBER;
DROP	TABLE BOOK;

-- EMP_COPY테이블만들기

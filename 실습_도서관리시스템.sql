    -- JOB테이블의 기본키를 먼저 실행
    CONSTRAINT FK_EMPCOPY_JOB FOREIGN KEY (JOB_CODE) REFERENCES JOB (JOB_CODE)
);
    
-- 테이블의 구조를 변경 - 기본키 지정

-- 경고메세지만 출력 후 다음 진행: 
DROP TABLE IF EXISTS EMP_COPY;
    
-- 테이블을 복사해서 만들기
-- SELECT문의 결과집합을 테이블로 생성 -> 결과집합의 데이터가 있다면 데이터까지 입력해줌

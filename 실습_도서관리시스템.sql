-- EMP_NAME 	VARCHAR(20)
-- EMP_NO 		CHAR(14)
-- JOB_CODE		CHAR(2)		FK(JOB테이블의 JOB_CODEF를 참조하고 이름은 FK_EMPCOPY_JOB) 

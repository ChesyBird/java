-- 일부 컬럼에 데이터를 입력
-- INSERT INTO 테이블이름 (컬럼지정, ..) VALUES (컬럼에 입력될 값, ...);
-- SYSDATE() : 현재 날짜와 시간을 반환하는 기본 내장함수
-- CURDATE() : 현재의 날짜만 반환
